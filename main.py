#!/usr/bin/env python3
"""Copy the prebuilt entry.png into the make.fun output directory.

Python 3.13. Output path: $MAKEFUN_OUTPUT_DIR/entry.png, default /output.
The image is generated by build_entry.py at build time; this script only
copies it, so the run is deterministic.
"""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "entry.png")


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, "entry.png")
    if not os.path.isfile(SRC):
        print("entry.png missing next to main.py", file=sys.stderr)
        return 1
    shutil.copyfile(SRC, dst)
    print("wrote", dst)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
